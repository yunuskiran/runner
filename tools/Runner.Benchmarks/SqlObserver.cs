using System.Xml.Linq;
using Microsoft.Data.SqlClient;
namespace Runner.Benchmarks;

public sealed class SqlObserver(string master, string database, string prefix) : IAsyncDisposable
{
    private bool owned;
    private readonly string session = "runner_bench_" + Guid.NewGuid().ToString("N");
    public async Task Start()
    {
        await using var db = new SqlConnection(master); await db.OpenAsync();
        await using var idCommand = new SqlCommand("SELECT DB_ID(@name)", db); idCommand.Parameters.AddWithValue("@name", database);
        var id = Convert.ToInt32(await idCommand.ExecuteScalarAsync());
        var events = new[] { "rpc_completed", "sql_batch_completed", "sql_statement_completed", "sp_statement_completed" }
            .Select(name => $"ADD EVENT sqlserver.{name}(WHERE ([sqlserver].[database_id]=({id}) AND [sqlserver].[like_i_sql_unicode_string]([sqlserver].[client_app_name],N'{prefix}%')))");
        // Names/prefix/database IDs are generated by this tool, never supplied as SQL identifiers by the caller.
        var sql = $"CREATE EVENT SESSION [{session}] ON SERVER " + string.Join(",", events) +
            " ADD TARGET package0.event_counter WITH (MAX_DISPATCH_LATENCY=1 SECONDS);";
        await using var create = new SqlCommand(sql, db); await create.ExecuteNonQueryAsync(); owned = true;
        await using var start = new SqlCommand($"ALTER EVENT SESSION [{session}] ON SERVER STATE=START;", db); await start.ExecuteNonQueryAsync();
    }
    public async Task<Observation> Read()
    {
        await using var db = new SqlConnection(master); await db.OpenAsync();
        await using var counter = new SqlCommand("""
            SELECT t.target_data, s.dropped_event_count FROM sys.dm_xe_session_targets t
            JOIN sys.dm_xe_sessions s ON s.address=t.event_session_address
            WHERE s.name=@session AND t.target_name='event_counter'
            """, db); counter.Parameters.AddWithValue("@session", session);
        string xml;
        await using (var reader = await counter.ExecuteReaderAsync())
        {
            if (!await reader.ReadAsync()) throw new InvalidOperationException("SQL XE event_counter is not running");
            xml = reader.GetString(0);
            if (Convert.ToInt64(reader.GetValue(1)) != 0) throw new InvalidOperationException("SQL XE dropped events; comparison would be incomplete");
        }
        var counts = XDocument.Parse(xml).Descendants().Where(x => x.Name.LocalName.Equals("Event", StringComparison.OrdinalIgnoreCase))
            .ToDictionary(x => x.Attribute("name")!.Value, x => long.Parse(x.Attribute("count")!.Value), StringComparer.OrdinalIgnoreCase);
        long Count(string name) => counts.GetValueOrDefault(name);
        await using var stats = new SqlCommand("""
            SELECT COALESCE(SUM(num_of_bytes_read),0),COALESCE(SUM(num_of_bytes_written),0)
              FROM sys.dm_io_virtual_file_stats(DB_ID(@database),NULL);
            SELECT COUNT(*) FROM sys.dm_exec_sessions WHERE program_name LIKE @prefix;
            SELECT COUNT(*) FROM sys.dm_exec_requests r JOIN sys.dm_exec_sessions s ON r.session_id=s.session_id WHERE s.program_name LIKE @prefix;
            """, db);
        stats.Parameters.AddWithValue("@database", database); stats.Parameters.AddWithValue("@prefix", prefix + "%");
        await using var data = await stats.ExecuteReaderAsync(); await data.ReadAsync();
        var reads = data.GetInt64(0); var writes = data.GetInt64(1); await data.NextResultAsync(); await data.ReadAsync(); var connections = data.GetInt32(0);
        await data.NextResultAsync(); await data.ReadAsync(); var active = data.GetInt32(0);
        return new(Count("rpc_completed"), Count("sql_batch_completed"), Count("sql_statement_completed"), Count("sp_statement_completed"), reads, writes, connections, active);
    }
    public async ValueTask DisposeAsync()
    {
        if (owned) await Config.Execute(master,
            $"IF EXISTS(SELECT 1 FROM sys.server_event_sessions WHERE name=N'{session}') DROP EVENT SESSION [{session}] ON SERVER;");
    }
}
